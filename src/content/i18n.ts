export function t(key: string, lang: Lang = 'ru'): string {
	return (I18N[lang] ?? I18N.ru)[key] ?? I18N.ru[key] ?? key;
}

// «от 1 250 000 ₴» / «from ₴1,250,000»; step — до скольких округлять
export function formatMoney(n: number, unit: string | undefined, lang: Lang = 'ru', step = 1000): string {
	const v = Math.round(n / step) * step;
	const num = v.toLocaleString(LOCALES[lang] ?? LOCALES.ru);
	const s = lang === 'en' ? t('from', lang) + ' ₴' + num : t('from', lang) + ' ' + num + ' ₴';
	return s + (unit === 'm2' ? '/' + t('m2', lang) : '');
}
